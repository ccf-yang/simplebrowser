/// Composition root for iOS.
///
/// This is the only layer allowed to touch FFI or platform channels. Each
/// adapter maps a stable error code onto the domain exceptions in
/// `domain/errors.dart`; no raw platform exception escapes this file.
final class IosAdapters {
  IosAdapters({
    MethodChannel? webViewChannel,
    MethodChannel? vaultChannel,
    MethodChannel? cookieChannel,
  }) : _webViewChannel =
           webViewChannel ?? const MethodChannel('browser_http/webview'),
       _vaultChannel =
           vaultChannel ?? const MethodChannel('browser_http/vault'),
       _cookieChannel =
           cookieChannel ?? const MethodChannel('browser_http/cookies');

  final MethodChannel _webViewChannel;
  final MethodChannel _vaultChannel;
  final MethodChannel _cookieChannel;

  late final TransportPort transport = _RustTransportAdapter();
  late final CookiePort cookies = _ChannelCookieAdapter(_cookieChannel);
  late final VaultPort vault = _ChannelVaultAdapter(_vaultChannel);
  late final WebViewPort webView = _ChannelWebViewAdapter(_webViewChannel);
}

/// Bridges [TransportPort] to the Rust core generated by flutter_rust_bridge.
final class _RustTransportAdapter implements TransportPort {
  static Future<void>? _rustInit;

  /// Loads the native library once per process.
  ///
  /// The Rust core is linked statically into the iOS binary, so symbols are
  /// resolved from the process image rather than from a `.dylib`.
  static Future<void> _ensureRust() async {
    final existing = _rustInit;
    if (existing != null) return existing;
    final future = RustLib.init(
      externalLibrary: ExternalLibrary.process(iKnowHowToUseIt: true),
    );
    _rustInit = future;
    try {
      await future;
    } on Object {
      _rustInit = null;
      rethrow;
    }
  }

  @override
  Future<TransportResponse> send(
    TransportRequest request, {
    CancelToken? cancelToken,
  }) async {
    await _ensureRust();

    _listenForCancel(request.id, cancelToken);

    try {
      final response = await ffi_transport.send(req: _toFfiRequest(request));

      return TransportResponse(
        statusCode: response.status,
        headers: <OrderedHeader>[
          for (final header in response.headers)
            OrderedHeader(header.name, header.value),
        ],
        body: response.body,
      );
    } on Object catch (error, stackTrace) {
      if (cancelToken?.isCancelled ?? false) {
        throw const CancelledException();
      }
      throw TransportException(
        code: _codeOf(error),
        message: error.toString(),
        cause: error,
        stackTrace: stackTrace,
      );
    }
  }

  @override
  Future<TransportStream> openStream(
    TransportRequest request, {
    CancelToken? cancelToken,
  }) async {
    await _ensureRust();
    _listenForCancel(request.id, cancelToken);

    final body = StreamController<List<int>>();
    final head = Completer<TransportStream>();
    late final StreamSubscription<ffi_transport.StreamEvent> subscription;

    subscription = ffi_transport
        .openStream(req: _toFfiRequest(request))
        .listen(
          (event) {
            switch (event.kind) {
              case 'head':
                if (!head.isCompleted) {
                  head.complete(
                    TransportStream(
                      statusCode: event.status ?? 0,
                      headers: <OrderedHeader>[
                        for (final header in event.headers)
                          OrderedHeader(header.name, header.value),
                      ],
                      body: body.stream,
                    ),
                  );
                }
              case 'data':
                body.add(event.bytes);
              case 'end':
                unawaited(body.close());
              default:
                break;
            }
          },
          onError: (Object error, StackTrace stackTrace) {
            if (cancelToken?.isCancelled ?? false) {
              const cancelled = CancelledException();
              if (!head.isCompleted) head.completeError(cancelled, stackTrace);
              body.addError(cancelled, stackTrace);
            } else {
              final mapped = TransportException(
                code: _codeOf(error),
                message: error.toString(),
                cause: error,
                stackTrace: stackTrace,
              );
              if (!head.isCompleted) head.completeError(mapped, stackTrace);
              body.addError(mapped, stackTrace);
            }
            unawaited(body.close());
          },
          onDone: () {
            if (!head.isCompleted) {
              head.completeError(
                const TransportException(
                  code: BrowserErrorCodes.transportProtocol,
                  message: 'Connection closed before response headers.',
                ),
              );
            }
            unawaited(body.close());
          },
          cancelOnError: true,
        );

    // Dropping the consumer must stop the Dart side immediately. Use a
    // CancelToken to also abort the native socket.
    body.onCancel = () => unawaited(subscription.cancel());

    return head.future;
  }

  @override
  Future<ProfileInfo> profileInfo(String profileId) async {
    await _ensureRust();
    final info = await ffi_profile.profileInfo(profileId: profileId);
    return ProfileInfo(
      profileId: info.profileId,
      family: info.family,
      userAgent: info.userAgent,
      clientHints: <String, String>{
        for (final header in info.clientHints) header.name: header.value,
      },
    );
  }

  @override
  Future<List<ProfileDescriptor>> listProfiles() async {
    await _ensureRust();
    final profiles = await ffi_profile.listProfiles();
    return <ProfileDescriptor>[
      for (final profile in profiles)
        ProfileDescriptor(
          id: profile.id,
          family: profile.family,
          browser: profile.browser,
          version: profile.version,
          iosCompatible: profile.iosCompatible,
        ),
    ];
  }

  @override
  Future<void> close() async {
    // Cached clients hold sockets; release them when the session ends. Skip
    // when Rust was never initialized.
    if (_rustInit == null) return;
    await _ensureRust();
    await ffi_transport.clearClients();
  }

  void _listenForCancel(String requestId, CancelToken? cancelToken) {
    if (requestId.isEmpty) return;
    cancelToken?.addListener(() {
      // Best effort: the request may already be finished.
      unawaited(ffi_transport.cancel(requestId: requestId).catchError((_) {}));
    });
  }

  static ffi_transport.TransportRequest _toFfiRequest(
    TransportRequest request,
  ) => ffi_transport.TransportRequest(
    id: request.id,
    method: request.method,
    url: request.uri.toString(),
    profileId: request.profileId,
    headers: <ffi_profile.HeaderPair>[
      for (final header in request.headers)
        ffi_profile.HeaderPair(name: header.name, value: header.value),
    ],
    body: request.body,
    proxyUrl: request.proxyUrl?.toString(),
    timeoutMs: request.timeout == null
        ? null
        : BigInt.from(request.timeout!.inMilliseconds),
    followRedirects: request.followRedirects,
    maxRedirects: request.maxRedirects,
  );

  static String _codeOf(Object error) {
    final message = error is AnyhowException ? error.message : error.toString();
    if (!message.startsWith('transport.')) {
      return BrowserErrorCodes.transportConnect;
    }
    final colon = message.indexOf(':');
    return colon > 0 ? message.substring(0, colon) : message;
  }
}

final class _ChannelCookieAdapter implements CookiePort {
  _ChannelCookieAdapter(this._channel);

  final MethodChannel _channel;

  @override
  Future<List<BrowserCookie>> get(Uri uri) async {
    final result = await _channel.invokeMethod<List<Object?>>(
      'get',
      <String, Object?>{'url': uri.toString()},
    );
    return (result ?? const <Object?>[])
        .map((e) => BrowserCookie.fromJson((e! as Map).cast<String, Object?>()))
        .toList(growable: false);
  }

  @override
  Future<void> setAll(Uri uri, List<BrowserCookie> cookies) =>
      _channel.invokeMethod<void>('setAll', <String, Object?>{
        'url': uri.toString(),
        'cookies': cookies.map((c) => c.toJson()).toList(growable: false),
      });

  @override
  Future<void> merge(Uri uri, List<BrowserCookie> cookies) =>
      _channel.invokeMethod<void>('merge', <String, Object?>{
        'url': uri.toString(),
        'cookies': cookies.map((c) => c.toJson()).toList(growable: false),
      });

  @override
  Future<void> removeAll(Uri uri) => _channel.invokeMethod<void>(
    'removeAll',
    <String, Object?>{'url': uri.toString()},
  );

  @override
  Future<void> clear() => _channel.invokeMethod<void>('clear');
}

final class _ChannelVaultAdapter implements VaultPort {
  _ChannelVaultAdapter(this._channel);

  final MethodChannel _channel;

  @override
  Future<SessionSnapshot?> read(String key) async {
    final json = await _channel.invokeMethod<String?>('read', <String, Object?>{
      'key': key,
    });
    if (json == null) return null;
    try {
      final decoded = jsonDecode(json);
      if (decoded is! Map) {
        throw const FormatException('snapshot is not a JSON object');
      }
      return SessionSnapshot.fromJson(decoded.cast<String, Object?>());
    } on FormatException catch (error, stackTrace) {
      throw VaultException(
        code: BrowserErrorCodes.vaultCorrupt,
        message: 'Stored session "$key" is corrupt.',
        cause: error,
        stackTrace: stackTrace,
      );
    }
  }

  @override
  Future<void> write(String key, SessionSnapshot snapshot) =>
      _channel.invokeMethod<void>('write', <String, Object?>{
        'key': key,
        'value': snapshot.toJson(),
      });

  @override
  Future<void> delete(String key) =>
      _channel.invokeMethod<void>('delete', <String, Object?>{'key': key});
}

final class _ChannelWebViewAdapter implements WebViewPort {
  _ChannelWebViewAdapter(this._channel) {
    _channel.setMethodCallHandler(_handleNativeCall);
  }

  final MethodChannel _channel;
  final StreamController<PageNetworkEvent> _networkEvents =
      StreamController<PageNetworkEvent>.broadcast();
  final StreamController<WebViewNavigationEvent> _navigationEvents =
      StreamController<WebViewNavigationEvent>.broadcast();
  final StreamController<WebViewLinkPress> _linkPressEvents =
      StreamController<WebViewLinkPress>.broadcast();
  final StreamController<WebViewVideoEvent> _videoEvents =
      StreamController<WebViewVideoEvent>.broadcast();

  Future<void> _handleNativeCall(MethodCall call) async {
    final raw = call.arguments;
    if (raw is! Map) return;
    switch (call.method) {
      case 'pageNetworkEvent':
        _networkEvents.add(
          PageNetworkEvent.fromJson(raw.cast<String, Object?>()),
        );
      case 'navigationEvent':
        _navigationEvents.add(
          WebViewNavigationEvent.fromJson(raw.cast<String, Object?>()),
        );
      case 'linkPress':
        _linkPressEvents.add(
          WebViewLinkPress.fromJson(raw.cast<String, Object?>()),
        );
      case 'videoEvent':
        _videoEvents.add(
          WebViewVideoEvent.fromJson(raw.cast<String, Object?>()),
        );
      default:
        break;
    }
  }

  @override
  Future<WebViewSession> create({
    required String userAgent,
    bool headless = true,
  }) async {
    final id = await _channel.invokeMethod<String>('create', <String, Object?>{
      'userAgent': userAgent,
      'headless': headless,
    });
    if (id == null) {
      throw const WebViewException(
        code: BrowserErrorCodes.webViewUnavailable,
        message: 'WKWebView could not be created.',
      );
    }
    return _ChannelWebViewSession(
      _channel,
      id,
      _networkEvents.stream,
      _navigationEvents.stream,
      _linkPressEvents.stream,
      _videoEvents.stream,
    );
  }

  @override
  bool get isVisibleModeSupported => true;
}

final class _ChannelWebViewSession implements WebViewSession {
  _ChannelWebViewSession(
    this._channel,
    this._id,
    this._allNetworkEvents,
    this._allNavigationEvents,
    this._allLinkPresses,
    this._allVideoEvents,
  );

  final MethodChannel _channel;
  final String _id;
  final Stream<PageNetworkEvent> _allNetworkEvents;
  final Stream<WebViewNavigationEvent> _allNavigationEvents;
  final Stream<WebViewLinkPress> _allLinkPresses;
  final Stream<WebViewVideoEvent> _allVideoEvents;

  @override
  String get id => _id;

  @override
  Stream<PageNetworkEvent> get networkEvents =>
      _allNetworkEvents.where((event) => event.sessionId == _id);

  @override
  Stream<WebViewNavigationEvent> get navigationEvents =>
      _allNavigationEvents.where((event) => event.sessionId == _id);

  @override
  Stream<WebViewLinkPress> get linkPresses =>
      _allLinkPresses.where((press) => press.sessionId == _id);

  @override
  Stream<WebViewVideoEvent> get videoEvents =>
      _allVideoEvents.where((event) => event.sessionId == _id);

  @override
  Future<Uint8List?> snapshot({int maxWidth = 360}) async {
    try {
      return await _channel.invokeMethod<Uint8List>(
        'snapshot',
        <String, Object?>{'id': _id, 'maxWidth': maxWidth},
      );
    } on PlatformException {
      // No page to render, or the view is between documents. A missing
      // thumbnail is not an error the host can act on.
      return null;
    }
  }

  @override
  Future<String> captureVideoFrame() async {
    try {
      return await _channel.invokeMethod<String>(
            'captureVideoFrame',
            <String, Object?>{'id': _id},
          ) ??
          'error: no result';
    } on PlatformException catch (error) {
      return 'error: ${error.message ?? error.code}';
    } on MissingPluginException {
      return 'error: unavailable';
    }
  }

  @override
  Future<WebViewLoadResult> load(
    Uri uri, {
    Duration? timeout,
    Map<String, String> headers = const <String, String>{},
  }) async {
    var call = _channel.invokeMethod<Map<Object?, Object?>>(
      'load',
      <String, Object?>{'id': _id, 'url': uri.toString(), 'headers': headers},
    );
    if (timeout != null) {
      call = call.timeout(
        timeout,
        onTimeout: () => throw const WebViewException(
          code: BrowserErrorCodes.webViewLoad,
          message: 'Timed out waiting for WKWebView navigation.',
        ),
      );
    }
    final result = await call;
    final status = result?['status'] as int?;
    return WebViewLoadResult(
      url: Uri.parse(result?['url'] as String? ?? uri.toString()),
      httpStatusCode: status == null || status == 0 ? null : status,
      title: result?['title'] as String?,
    );
  }

  @override
  Future<void> navigate(
    Uri uri, {
    Map<String, String> headers = const <String, String>{},
  }) => _channel.invokeMethod<void>('navigate', <String, Object?>{
    'id': _id,
    'url': uri.toString(),
    'headers': headers,
  });

  @override
  Future<void> setUserAgent(String? userAgent) => _channel.invokeMethod<void>(
    'setUserAgent',
    <String, Object?>{'id': _id, 'userAgent': userAgent},
  );

  @override
  Future<void> setCookie(Uri uri, String cookieHeader) =>
      _channel.invokeMethod<void>('setCookie', <String, Object?>{
        'id': _id,
        'url': uri.toString(),
        'cookie': cookieHeader,
      });

  @override
  Future<bool> canGoBack() async =>
      await _channel.invokeMethod<bool>('canGoBack', <String, Object?>{
        'id': _id,
      }) ??
      false;

  @override
  Future<bool> canGoForward() async =>
      await _channel.invokeMethod<bool>('canGoForward', <String, Object?>{
        'id': _id,
      }) ??
      false;

  @override
  Future<void> goBack() =>
      _channel.invokeMethod<void>('goBack', <String, Object?>{'id': _id});

  @override
  Future<void> goForward() =>
      _channel.invokeMethod<void>('goForward', <String, Object?>{'id': _id});

  @override
  Future<void> reload() =>
      _channel.invokeMethod<void>('reload', <String, Object?>{'id': _id});

  @override
  Future<void> stopLoading() =>
      _channel.invokeMethod<void>('stopLoading', <String, Object?>{'id': _id});

  @override
  Future<String?> currentUrl() => _channel.invokeMethod<String?>(
    'currentUrl',
    <String, Object?>{'id': _id},
  );

  @override
  Future<String?> currentTitle() => _channel.invokeMethod<String?>(
    'currentTitle',
    <String, Object?>{'id': _id},
  );

  @override
  Future<int?> lastStatusCode() =>
      _channel.invokeMethod<int?>('lastStatus', <String, Object?>{'id': _id});

  @override
  Future<List<WebResourceTiming>> resourceTimings() async {
    final result = await _channel.invokeMethod<List<Object?>>(
      'resourceTimings',
      <String, Object?>{'id': _id},
    );
    return (result ?? const <Object?>[])
        .map(
          (e) =>
              WebResourceTiming.fromJson((e! as Map).cast<String, Object?>()),
        )
        .toList(growable: false);
  }

  @override
  Future<Object?> evaluate(String script) => _channel.invokeMethod<Object?>(
    'evaluate',
    <String, Object?>{'id': _id, 'script': script},
  );

  @override
  Future<List<BrowserCookie>> exportCookies(Uri uri) async {
    final result = await _channel.invokeMethod<List<Object?>>(
      'exportCookies',
      <String, Object?>{'id': _id, 'url': uri.toString()},
    );
    return (result ?? const <Object?>[])
        .map((e) => BrowserCookie.fromJson((e! as Map).cast<String, Object?>()))
        .toList(growable: false);
  }

  @override
  Future<Map<String, String>> exportLocalStorage(Uri origin) async {
    final result = await _channel.invokeMethod<Map<Object?, Object?>>(
      'exportLocalStorage',
      <String, Object?>{'id': _id, 'origin': origin.origin},
    );
    return <String, String>{
      for (final entry in (result ?? const <Object?, Object?>{}).entries)
        entry.key! as String: entry.value! as String,
    };
  }

  @override
  Future<void> importLocalStorage(Uri origin, Map<String, String> values) =>
      _channel.invokeMethod<void>('importLocalStorage', <String, Object?>{
        'id': _id,
        'origin': origin.origin,
        'values': values,
      });

  @override
  Future<String> currentUserAgent() async =>
      await _channel.invokeMethod<String>('currentUserAgent', <String, Object?>{
        'id': _id,
      }) ??
      '';

  @override
  Future<String> setDebugOverlay({
    required bool enabled,
    String? source,
    double displaySize = 50,
  }) async {
    // Deliberately not `invokeMethod<String>`: a framework built before the
    // status became a string answers with a bool, and that cast would throw
    // before the host can say what happened. Normalise instead.
    final raw = await _channel.invokeMethod<Object?>(
      'setDebugOverlay',
      <String, Object?>{
        'id': _id,
        'enabled': enabled,
        'source': source,
        'displaySize': displaySize,
      },
    );
    if (raw is String) return raw;
    if (raw is bool) return raw ? 'ok|legacy-native' : 'failed|legacy-native';
    return raw == null ? 'ok|legacy-native' : '$raw';
  }

  @override
  Future<void> setPageNetworkEnabled(bool enabled) =>
      _channel.invokeMethod<void>('setPageNetwork', <String, Object?>{
        'id': _id,
        'enabled': enabled,
      });

  @override
  Future<String> applyContentRuleList({
    required String identifier,
    String? encodedRules,
  }) async {
    final raw = await _channel.invokeMethod<String>(
      'applyContentRuleList',
      <String, Object?>{
        'id': _id,
        'identifier': identifier,
        'encodedRules': encodedRules,
      },
    );
    return raw ?? 'missing';
  }

  @override
  Future<void> setContentBlockingEnabled(bool enabled) =>
      _channel.invokeMethod<void>('setContentBlockingEnabled', <String, Object?>{
        'id': _id,
        'enabled': enabled,
      });

  @override
  Future<void> setDebugDisplaySize(double displaySize) =>
      _channel.invokeMethod<void>('setDebugDisplaySize', <String, Object?>{
        'id': _id,
        'displaySize': displaySize,
      });

  @override
  Future<void> setNavigationPolicy({
    bool blockExternal = true,
    bool reissueTaps = true,
    bool askExternal = false,
    List<String> allowSchemes = const <String>[],
    List<String> denySchemes = const <String>[],
  }) => _channel.invokeMethod<void>('setNavigationPolicy', <String, Object?>{
    'id': _id,
    'blockExternal': blockExternal,
    'reissueTaps': reissueTaps,
    'askExternal': askExternal,
    'allowSchemes': allowSchemes,
    'denySchemes': denySchemes,
  });

  @override
  Future<void> openExternal(Uri uri) =>
      _channel.invokeMethod<void>('openExternal', <String, Object?>{
        'id': _id,
        'url': uri.toString(),
      });

  @override
  Future<void> dispose() =>
      _channel.invokeMethod<void>('dispose', <String, Object?>{'id': _id});
}
